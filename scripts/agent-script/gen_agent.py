def subagent(name, label, desc, actions_defs, instructions, bindings, extra=""):
    S = [f"subagent {name}:", f"{I}label: {q(label)}", f"{I}description: {q(desc)}", "", f"{I}actions:"]
    S += actions_defs
    S += ["", f"{I}reasoning:", f"{I*2}instructions: ->", instructions, f"{I*2}actions:", bindings]
    if extra:
        S += [extra]
    return "\n".join(S) + "\n"


